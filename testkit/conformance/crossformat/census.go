package crossformat

import (
	"bytes"
	"cmp"
	"fmt"
	"maps"
	"slices"
	"strconv"
	"strings"
	"unicode/utf8"
)

// censusExamples is how many example keys or leaves the census lists per
// difference class.
const censusExamples = 10

// Census renders the census of results, with each leg's reason taken from
// table, as Markdown. The output depends only on its inputs and is sorted
// everywhere, so the committed CENSUS.md can be compared byte for byte with
// what the harness generates.
func Census(results []SetResult, table map[string]map[Leg]Record) []byte {
	sorted := slices.Clone(results)
	slices.SortFunc(sorted, func(a, b SetResult) int { return strings.Compare(a.Set, b.Set) })

	var b bytes.Buffer
	b.WriteString(censusHeader)
	b.WriteString("## Summary\n\n| Set | Leg | Outcome |\n|---|---|---|\n")
	for _, res := range sorted {
		for _, lr := range res.Legs {
			outcome := lr.Outcome.String()
			if lr.Outcome.Refused != "" {
				outcome = "refused"
			}
			fmt.Fprintf(&b, "| %s | %s | %s |\n", res.Set, lr.Leg, outcome)
		}
	}
	for _, res := range sorted {
		fmt.Fprintf(&b, "\n## %s\n", res.Set)
		for _, lr := range res.Legs {
			writeLeg(&b, lr, table[res.Set])
		}
	}
	return []byte(strings.ReplaceAll(b.String(), "\u2014", "-"))
}

const censusHeader = `# PROBE-105 cross-format census

This file is generated by the PROBE-105 harness in this directory. Do not edit it by hand. Regenerate it with:

    go test ./testkit/conformance/crossformat/ -run TestCensus -update

Each set under testkit/corpus/crossformat/ gives one composition in two or more formats. The harness runs every leg whose two formats a set carries and compares the result with a reference side:

| Leg | What runs | Reference side |
|---|---|---|
| json-xml | canonical JSON and canonical XML each decode and re-encode as canonical JSON, compared leaf by leaf | the canonical JSON |
| canonical-flat | the decoded canonical document, encoded as FLAT, compared key by key | the upstream FLAT |
| flat-canonical | the upstream FLAT, decoded with its metadata kept, re-encoded as canonical JSON, compared leaf by leaf | the canonical document |
| flat-structured | the upstream FLAT restructured as STRUCTURED without a template, compared leaf by leaf | the upstream STRUCTURED |
| structured-flat | the upstream STRUCTURED flattened, decoded and encoded as FLAT, compared key by key | the upstream FLAT decoded and encoded the same way |

A leaf is a JSON pointer to a scalar, an empty object or an empty array, with its value as JSON text. Every FLAT comparison holds composition metadata out on both sides with the PROBE-086 hold-out. Every FLAT decode removes each key family the codec refuses and retries; the keys it removed are listed as information, since a removed key shows up in the comparison as missing.

An outcome is either a refusal, the codec error that ended the leg, or four counts: compared (the size of the reference side), missing (reference keys absent from ours), extra (our keys absent from the reference) and altered (keys on both sides with different values). Each outcome must equal the one recorded in recorded.go, and the reason shown is the recorded one.

`

// writeLeg renders one leg's section.
func writeLeg(b *bytes.Buffer, lr LegResult, recs map[Leg]Record) {
	fmt.Fprintf(b, "\n### %s\n\n", lr.Leg)
	rec, recorded := recs[lr.Leg]
	if lr.Outcome.Refused != "" {
		b.WriteString("- Outcome: refused\n")
		fmt.Fprintf(b, "- Error: %s\n", code(Abbreviate(StableError(lr.Outcome.Refused))))
		if recorded && rec.Outcome.Refused != "" {
			fmt.Fprintf(b, "- Recorded as an error containing %s\n", code(rec.Outcome.Refused))
		}
	} else {
		fmt.Fprintf(b, "- Outcome: %s\n", lr.Outcome)
	}
	switch {
	case !recorded:
		b.WriteString("- Reason: no record\n")
	case rec.Reason != "":
		fmt.Fprintf(b, "- Reason: %s\n", rec.Reason)
	}
	writeKeys(b, "Missing", lr.MissingKeys)
	writeKeys(b, "Extra", lr.ExtraKeys)
	if n := len(lr.Alterations); n > 0 {
		fmt.Fprintf(b, "- Altered (%s):\n", countOf(n))
		for _, a := range lr.Alterations[:min(n, censusExamples)] {
			fmt.Fprintf(b, "  - %s: reference %s, ours %s\n", code(a.Key), code(abbreviateValue(a.Reference)), code(abbreviateValue(a.Ours)))
		}
	}
	writeRefusals(b, lr)
}

// writeKeys renders one difference class's example keys.
func writeKeys(b *bytes.Buffer, label string, keys []string) {
	if len(keys) == 0 {
		return
	}
	fmt.Fprintf(b, "- %s (%s):\n", label, countOf(len(keys)))
	for _, k := range keys[:min(len(keys), censusExamples)] {
		fmt.Fprintf(b, "  - %s\n", code(k))
	}
}

// writeRefusals renders what the leg's reducing decodes removed, grouped by
// reason.
func writeRefusals(b *bytes.Buffer, lr LegResult) {
	if len(lr.Refusals) == 0 {
		return
	}
	keys := map[string]int{}
	for _, r := range lr.Refusals {
		keys[r.Reason] += r.Keys
	}
	reasons := slices.Collect(maps.Keys(keys))
	slices.SortFunc(reasons, func(x, y string) int { return cmp.Or(cmp.Compare(keys[y], keys[x]), strings.Compare(x, y)) })
	fmt.Fprintf(b, "- Reducing decode removed %s:\n", plural(lr.Excluded(), "key"))
	for _, r := range reasons {
		fmt.Fprintf(b, "  - %d: %s\n", keys[r], r)
	}
}

// plural renders n of noun, adding an s unless n is one.
func plural(n int, noun string) string {
	if n == 1 {
		return "1 " + noun
	}
	return strconv.Itoa(n) + " " + noun + "s"
}

// countOf says how many entries a class has and how many the census lists.
func countOf(n int) string {
	if n <= censusExamples {
		return strconv.Itoa(n)
	}
	return fmt.Sprintf("%d, first %d shown", n, censusExamples)
}

// code renders s as a Markdown code span, with a fence longer than any run of
// backticks inside it.
func code(s string) string {
	fence := "`"
	for strings.Contains(s, fence) {
		fence += "`"
	}
	if strings.HasPrefix(s, "`") || strings.HasSuffix(s, "`") {
		s = " " + s + " "
	}
	return fence + s + fence
}

// longToken is how long a run of non-space characters may be before
// [Abbreviate] shortens it.
const longToken = 100

// Abbreviate shortens every run of non-space characters longer than 100
// runes in msg, such as an encoded payload a codec error quotes, to its first
// 40 runes and "...", so a message stays readable in a report.
func Abbreviate(msg string) string {
	fields := strings.Split(msg, " ")
	for i, f := range fields {
		if utf8.RuneCountInString(f) > longToken {
			fields[i] = string([]rune(f)[:40]) + "..."
		}
	}
	return strings.Join(fields, " ")
}

// abbreviateValue shortens a value longer than 60 runes to its first 50 and
// "...", so an altered narrative or payload does not swamp the census.
func abbreviateValue(v string) string {
	if utf8.RuneCountInString(v) <= 60 {
		return v
	}
	return string([]rune(v)[:50]) + "..."
}
