// RenderRMInfoFile produces the `openehr/rm/rminfo/lookup_gen.go`
// data table from a planned RM emission. It walks the class universe
// ([rmInfoUniverse]), computes the effective property set (own +
// inherited from ancestors, ancestor-order preserved, own overrides
// parent on same name), and emits a single `defaultData` map literal.
//
// Per class it emits both layers rminfo answers over:
//   - the inheritance-FLATTENED attribute set, plus the `DeclaredIn`
//     site the fold would otherwise erase;
//   - the class-graph facts, `Abstract` and `Parents`, the latter
//     filtered to the universe so the emitted graph stays closed.
//
// A second map literal, `functionData`, lists per class the BMM
// functions it declares or inherits that are properties neither of the
// class nor of a class descending from it ([effectiveFunctions]), which
// `rminfo.IsNonStorableAttr` names; a class with none has no entry.
//
// Returns nil when the target is not the RM target (rminfo is only
// generated alongside RM). The caller is expected to gate by target
// before invoking.
//
// Output is deterministic: outer map keys sorted alphabetically,
// inner attribute maps sorted alphabetically, AttrOrder preserves
// the merged BMM declaration order (ancestors first, then own), and
// Parents preserves the BMM ancestor declaration order. Zero-valued
// `Abstract` / `Parents` keys are omitted rather than emitted false
// and empty. Function names are sorted.
func RenderRMInfoFile(plan *Plan) ([]byte, error) {
	if plan.Target.GoPackage != "rm" {
		return nil, nil
	}

	type entry struct {
		className string
		attrs     map[string]rmAttr
		order     []string
		abstract  bool
		parents   []string
		functions []string
	}

	classNames := rmInfoUniverse(plan)
	inUniverse := make(map[string]bool, len(classNames))
	for _, name := range classNames {
		inUniverse[name] = true
	}

	entries := make([]entry, 0, len(classNames))
	for _, name := range classNames {
		// One lookup, passed down: rmInfoUniverse only yields plan keys, so
		// the class is present by construction, and hoisting it keeps the
		// two uses from disagreeing about whether they need a guard.
		pc := plan.Classes[name]
		attrs, order := effectiveProperties(plan, name)
		entries = append(entries, entry{
			className: name,
			attrs:     attrs,
			order:     order,
			abstract:  pc.Class.IsAbstract(),
			parents:   rmInfoParents(pc, inUniverse),
			functions: effectiveFunctions(plan, name),
		})
	}

	var body bytes.Buffer
	body.WriteString("// Code generated by bmmgen; DO NOT EDIT.\n")
	fmt.Fprintf(&body, "// Source: %s\n\n", plan.Target.SourceLabel)
	body.WriteString("package rminfo\n\n")
	body.WriteString("var defaultData = map[string]ClassMeta{\n")
	for _, e := range entries {
		fmt.Fprintf(&body, "\t%q: {\n", e.className)
		body.WriteString("\t\tAttributes: map[string]AttrMeta{\n")
		// Inner map deterministic on name.
		innerNames := make([]string, 0, len(e.attrs))
		for n := range e.attrs {
			innerNames = append(innerNames, n)
		}
		slices.Sort(innerNames)
		for _, n := range innerNames {
			a := e.attrs[n]
			fmt.Fprintf(&body, "\t\t\t%q: {TypeName: %q, Required: %t, Container: %t, DeclaredIn: %q},\n",
				n, a.typeName, a.required, a.container, a.declaredIn)
		}
		body.WriteString("\t\t},\n")
		body.WriteString("\t\tAttrOrder: []string{")
		for i, n := range e.order {
			if i > 0 {
				body.WriteString(", ")
			}
			fmt.Fprintf(&body, "%q", n)
		}
		body.WriteString("},\n")
		// Abstract and Parents are emitted only when they carry
		// information: a false flag and an empty parent list are the
		// zero values, and omitting them keeps the generated table
		// readable without changing what it says.
		if e.abstract {
			body.WriteString("\t\tAbstract: true,\n")
		}
		if len(e.parents) > 0 {
			body.WriteString("\t\tParents: []string{")
			for i, n := range e.parents {
				if i > 0 {
					body.WriteString(", ")
				}
				fmt.Fprintf(&body, "%q", n)
			}
			body.WriteString("},\n")
		}
		body.WriteString("\t},\n")
	}
	body.WriteString("}\n\n")
	body.WriteString("// functionData lists, for each class above that has one, the BMM functions\n")
	body.WriteString("// the class declares or inherits that are properties neither of the class\n")
	body.WriteString("// nor of a class descending from it, sorted. No serialization of an instance\n")
	body.WriteString("// of the class carries one, so IsNonStorableAttr names them.\n")
	body.WriteString("var functionData = map[string][]string{\n")
	for _, e := range entries {
		if len(e.functions) == 0 {
			continue
		}
		fmt.Fprintf(&body, "\t%q: {", e.className)
		for i, n := range e.functions {
			if i > 0 {
				body.WriteString(", ")
			}
			fmt.Fprintf(&body, "%q", n)
		}
		body.WriteString("},\n")
	}
	body.WriteString("}\n")
	formatted, err := format.Source(body.Bytes())
	if err != nil {
		return body.Bytes(), fmt.Errorf("gofmt rminfo/lookup_gen.go: %w", err)
	}
	return formatted, nil
}

// rmAttr is an internal lightweight mirror of rminfo.AttrMeta used
// during plan walking. We avoid importing the rminfo package
// directly to keep the import direction one-way (rminfo does NOT
// depend on bmmgen).
type rmAttr struct {
	typeName  string
	required  bool
	container bool
	// declaredIn is the class whose BMM declaration this attribute came
	// from, recorded by the fold in [effectiveProperties] rather than
	// re-derived afterwards (REQ-048): a second, independent walk could
	// disagree with the shape fields above, and two answers to "where
	// does this attribute come from" is the defect being fixed.
	declaredIn string
}

// rmInfoUniverse returns the sorted class universe REQ-048 defines: every
// class in the plan the generator emits a Go type for. Enumerations,
// primitives, and classes external to the target are out; classes that
// carry no attributes of their own or inherited (DATA_VALUE, PATHABLE, the
// support-service interfaces) are IN — a descendant expansion rooted at an
// abstract class is unanswerable while that class is absent from the table.
//
// The wholesale generator exclusions (org.openehr.rm.ehr_extract per
// REQ-041) never reach here: BuildPlan drops them.
func rmInfoUniverse(plan *Plan) []string {
	names := make([]string, 0, len(plan.Classes))
	for name, pc := range plan.Classes {
		if pc.External || pc.IsPrimitive {
			continue
		}
		if _, ok := pc.Class.(*bmm.Enumeration); ok {
			continue
		}
		names = append(names, name)
	}
	slices.Sort(names)
	return names
}

// rmInfoParents returns className's immediate parents in BMM declaration
// order, filtered to inUniverse and de-duplicated.
//
// Filtering is what keeps the emitted graph closed over the universe
// (REQ-048): what it drops is exactly the excluded kinds — the base schema's
// primitive_types entries that appear as BMM ancestors (`Any`, `Ordered`,
// `Interval`, `Iso8601_type` and the four `Iso8601_*` value types) plus the
// PROPORTION_KIND enumeration. It costs no RM edge, because every class that
// names one of those also names an RM ancestor beside it (DV_ORDERED is
// `[DATA_VALUE, Ordered]`, DV_INTERVAL is `[DATA_VALUE, Interval]`,
// DV_PROPORTION is `[PROPORTION_KIND, DV_AMOUNT]`) and that ancestor survives.
// Four classes are left with no in-universe ancestor and become roots —
// PATHABLE, Point_interval, Proper_interval, Iso8601_timezone — each losing a
// foundation edge, none an RM one. PROBE-094 pins that set.
func rmInfoParents(pc *PlannedClass, inUniverse map[string]bool) []string {
	var out []string
	for _, anc := range pc.Class.Ancestors() {
		if !inUniverse[anc] || slices.Contains(out, anc) {
			continue
		}
		out = append(out, anc)
	}
	return out
}

// effectiveProperties returns the merged (own + inherited) property
// set of a BMM class. Properties are collected ancestor-first via a
// depth-first walk; when a property name appears at multiple levels
// the most-derived definition wins, but its position in AttrOrder is
// fixed by the FIRST ancestor that declared it (BMM-spec linearisation
// rule: redefinition keeps the parent's slot).
//
// Each returned attribute also carries the class that supplied it
// (`rmAttr.declaredIn`), recorded here rather than re-derived later so the
// site and the shape come from one decision (REQ-048).
func effectiveProperties(plan *Plan, className string) (map[string]rmAttr, []string) {
	out := make(map[string]rmAttr)
	var order []string
	seen := make(map[string]bool)
	visitedClass := make(map[string]bool)

	var visit func(name string)
	visit = func(name string) {
		if visitedClass[name] {
			return
		}
		visitedClass[name] = true
		pc, ok := plan.Classes[name]
		if !ok {
			return
		}
		// Visit ancestors first so their property names land earlier
		// in AttrOrder. Multiple inheritance is rare in the openEHR
		// BMM; when it occurs we follow declaration order of
		// Ancestors().
		for _, anc := range pc.Class.Ancestors() {
			visit(anc)
		}
		props, propOrder := classProperties(pc.Class)
		for _, propName := range propOrder {
			prop := props[propName]
			attr, ok := propToAttr(prop)
			if !ok {
				continue
			}
			// Most-derived wins on shape/required/container — and on the
			// declaration site, recorded in the same assignment so the
			// two cannot drift apart (REQ-048).
			attr.declaredIn = name
			out[propName] = attr
			if !seen[propName] {
				seen[propName] = true
				order = append(order, propName)
			}
		}
	}
	visit(className)
	return out, order
}

// effectiveFunctions returns, sorted, the names of the BMM functions
// className declares or inherits, less every name that is a property of
// the class or of a class descending from it, declared there or inherited
// (REQ-112 Driver). A function an ancestor declares that the class
// declares as a property, as DV_QUANTITY does DV_QUANTIFIED's magnitude,
// is the class's property, not its function; and that magnitude is no
// function of DV_AMOUNT either, since its descendant DV_QUANTITY stores
// it. A name is left out only when no instance the class denotes stores
// it.
//
// The walk reads the merged schema rather than the planned classes, so
// an ancestor the class universe leaves out, a primitive_types entry
// such as Any or Iso8601_duration, still gives the class its functions
// and its properties. A plan built by hand with no schema is walked over
// its planned classes.
func effectiveFunctions(plan *Plan, className string) []string {
	functions := make(map[string]bool)
	for _, c := range declaredAncestry(plan, className) {
		for n := range classFunctions(c) {
			functions[n] = true
		}
	}
	for _, name := range declaredClassNames(plan) {
		ancestry := declaredAncestry(plan, name)
		if _, descends := ancestry[className]; !descends {
			continue
		}
		for _, c := range ancestry {
			props, _ := classProperties(c)
			for n := range props {
				delete(functions, n)
			}
		}
	}
	out := slices.Collect(maps.Keys(functions))
	slices.Sort(out)
	return out
}

// declaredAncestry returns, by name, the class declared under name
// ([declaredClass]) and every class it descends from, transitively. An
// ancestor that is not declared ends that branch of the walk.
func declaredAncestry(plan *Plan, name string) map[string]bmm.Class {
	out := make(map[string]bmm.Class)
	var visit func(name string)
	visit = func(name string) {
		if _, seen := out[name]; seen {
			return
		}
		c, ok := declaredClass(plan, name)
		if !ok {
			return
		}
		out[name] = c
		for _, anc := range c.Ancestors() {
			visit(anc)
		}
	}
	visit(name)
	return out
}

// declaredClassNames returns every name [declaredClass] answers for: the
// classes and primitive types of the merged schema, or, for a plan that
// carries no schema, its planned classes. The order is unspecified.
func declaredClassNames(plan *Plan) []string {
	if plan.Schema != nil {
		names := slices.Collect(maps.Keys(plan.Schema.ClassDefinitions))
		return slices.AppendSeq(names, maps.Keys(plan.Schema.PrimitiveTypes))
	}
	return slices.Collect(maps.Keys(plan.Classes))
}

// declaredClass returns the class the merged schema of plan declares
// under name ([schemaClass]), or, for a plan that carries no schema, the
// planned class of that name.
func declaredClass(plan *Plan, name string) (bmm.Class, bool) {
	if plan.Schema != nil {
		return schemaClass(plan.Schema, name)
	}
	pc, ok := plan.Classes[name]
	if !ok {
		return nil, false
	}
	return pc.Class, true
}

// classFunctions returns the BMM functions a class declares itself.
// Every class kind can declare functions, an enumeration included
// (PROPORTION_KIND's valid_proportion_kind).
func classFunctions(c bmm.Class) map[string]*bmm.Function {
	switch cls := c.(type) {
	case *bmm.SimpleClass:
		return cls.Functions
	case *bmm.Interface:
		return cls.Functions
	case *bmm.Enumeration:
		return cls.Functions
	default:
		return nil
	}
}

// classProperties returns the BMM (properties, declarationOrder) of
// a class. SimpleClass and Interface carry properties; Enumeration
// does not (returns nil/nil).
func classProperties(c bmm.Class) (map[string]bmm.Property, []string) {
	switch cls := c.(type) {
	case *bmm.SimpleClass:
		return cls.Properties, cls.PropertyOrder
	case *bmm.Interface:
		return cls.Properties, cls.PropertyOrder
	default:
		return nil, nil
	}
}

// propToAttr unpacks a BMM Property into the rminfo AttrMeta shape.
// Returns ok=false for properties we cannot translate (typeless
// generic-parameter open properties without a concrete bound).
//
// IsMandatory is exposed via Go struct embedding (propertyCommon
// is embedded in each concrete Property variant), so the field
// access on the concrete type compiles even though the Property
// interface does not declare it.
func propToAttr(p bmm.Property) (rmAttr, bool) {
	switch v := p.(type) {
	case *bmm.SingleProperty:
		return rmAttr{
			typeName:  v.TypeName,
			required:  v.IsMandatory,
			container: false,
		}, true
	case *bmm.SinglePropertyOpen:
		return rmAttr{
			typeName:  v.TypeName,
			required:  v.IsMandatory,
			container: false,
		}, true
	case *bmm.ContainerProperty:
		return rmAttr{
			typeName:  containerInnerType(v.TypeDef),
			required:  containerRequired(v.Cardinality, v.IsMandatory),
			container: true,
		}, true
	case *bmm.GenericProperty:
		return rmAttr{
			typeName:  genericRootType(v.TypeDef),
			required:  v.IsMandatory,
			container: false,
		}, true
	default:
		return rmAttr{}, false
	}
}

// containerInnerType extracts the BMM type name of a container
// property's element. Falls back to a sentinel "Any" when the type
// definition is malformed (should not occur on the pinned BMM).
func containerInnerType(td *bmm.ContainerType) string {
	if td == nil || td.TypeDef == nil {
		return "Any"
	}
	switch inner := td.TypeDef.(type) {
	case *bmm.SimpleType:
		return inner.TypeName
	case *bmm.GenericType:
		return inner.RootType
	case *bmm.ContainerType:
		// Nested containers are rare in the openEHR BMM; report the
		// innermost element type so downstream consumers see a
		// concrete RM class name when they descend.
		return containerInnerType(inner)
	default:
		return "Any"
	}
}

// containerRequired reports whether a container property is required.
// True when:
//   - the propertyCommon.is_mandatory flag is set, OR
//   - the cardinality lower bound is >= 1.
func containerRequired(card *bmm.Cardinality, mandatory bool) bool {
	if mandatory {
		return true
	}
	if card != nil && card.Lower >= 1 {
		return true
	}
	return false
}

// genericRootType returns the BMM root type name for a GenericType.
// Used by GenericProperty to expose the outer class name (e.g.
// "INTERVAL" for an INTERVAL[DV_QUANTITY] property).
func genericRootType(td bmm.Type) string {
	if td == nil {
		return "Any"
	}
	switch t := td.(type) {
	case *bmm.GenericType:
		return t.RootType
	case *bmm.SimpleType:
		return t.TypeName
	default:
		return "Any"
	}
}
