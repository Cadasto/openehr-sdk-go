// TestRenderRMAccessFile_REQ171_Deterministic pins that the output is
// gofmt'd and byte-identical across runs.
func TestRenderRMAccessFile_REQ171_Deterministic(t *testing.T) {
	plan, out, _ := rmAccessOutput(t)
	again, err := RenderRMAccessFile(plan)
	if err != nil {
		t.Fatalf("RenderRMAccessFile(RM) second run: %v", err)
	}
	if !bytes.Equal(out, again) {
		t.Error("RenderRMAccessFile(RM) differs between two runs on one plan")
	}
	formatted, err := format.Source(out)
	if err != nil || !bytes.Equal(formatted, out) {
		t.Errorf("RenderRMAccessFile(RM) output is not gofmt'd (format error %v)", err)
	}
	if !bytes.HasPrefix(out, []byte("// Code generated by bmmgen; DO NOT EDIT.\n")) {
		t.Error("RenderRMAccessFile(RM) output lacks the generated-code header")
	}
}

// TestRenderRMAccessFile_REQ171_CoversTheRegistry pins that covers lists, in
// pointer and value form, exactly the Go types the reverse registry
// recognises for the classes the type registry decodes, and that every arm's
// readers answer exactly the attributes the class declares (the fold rminfo
// is generated from), containers through multiple and every other attribute
// through single.
func TestRenderRMAccessFile_REQ171_CoversTheRegistry(t *testing.T) {
	plan, _, file := rmAccessOutput(t)

	type armWant struct {
		suffix string
		single []string
		multi  []string
	}
	want := map[string]bool{}
	var arms []armWant
	for _, pc := range plan.ConcreteClasses {
		names, err := reverseRegistryArms(plan, pc)
		if err != nil {
			t.Fatalf("reverseRegistryArms(%s): %v", pc.BMMName, err)
		}
		attrs, _ := effectiveProperties(plan, pc.BMMName)
		var single, multi []string
		for _, name := range sortedStringKeys(attrs) {
			if attrs[name].container {
				multi = append(multi, name)
			} else {
				single = append(single, name)
			}
		}
		for _, arm := range names {
			typ, err := parseGoType(arm)
			if err != nil {
				t.Fatalf("parseGoType(%q): %v", arm, err)
			}
			want[typ.qualified()] = true
			want["*"+typ.qualified()] = true
			arms = append(arms, armWant{suffix: typ.suffix(), single: single, multi: multi})
		}
	}
	if len(plan.ConcreteClasses) < 100 || len(arms) <= len(plan.ConcreteClasses) {
		t.Fatalf("%d concrete classes and %d arms, want the full RM registry with its generic instantiations", len(plan.ConcreteClasses), len(arms))
	}

	covers := funcDecl(file, "covers")
	if covers == nil {
		t.Fatal("rendered file has no covers function")
	}
	got := map[string]bool{}
	ast.Inspect(covers, func(n ast.Node) bool {
		if cc, ok := n.(*ast.CaseClause); ok {
			for _, e := range cc.List {
				got[types.ExprString(e)] = true
			}
		}
		return true
	})
	for _, typ := range slices.Sorted(maps.Keys(want)) {
		if !got[typ] {
			t.Errorf("covers does not list %s, which the registry recognises", typ)
		}
	}
	for _, typ := range slices.Sorted(maps.Keys(got)) {
		if !want[typ] {
			t.Errorf("covers lists %s, which the registry does not recognise", typ)
		}
	}

	for _, arm := range arms {
		for _, reader := range []struct {
			prefix string
			attrs  []string
		}{{"single", arm.single}, {"multiple", arm.multi}} {
			fd := funcDecl(file, reader.prefix+arm.suffix)
			if fd == nil {
				if len(reader.attrs) > 0 {
					t.Errorf("no %s%s for the attributes %q", reader.prefix, arm.suffix, reader.attrs)
				}
				continue
			}
			got := slices.Sorted(maps.Keys(caseBodies(t, fd)))
			if !slices.Equal(got, reader.attrs) {
				t.Errorf("%s%s answers %q, want %q", reader.prefix, arm.suffix, got, reader.attrs)
			}
		}
	}
}

// TestRenderRMAccessFile_REQ171_Readings pins, on the pinned RM, which
// reading the generator chooses for one attribute of each kind: the reading
// by Go kind, a content rule by declared type, a zero test, the three fixed
// readings and the five attributes handed back in another shape.
func TestRenderRMAccessFile_REQ171_Readings(t *testing.T) {
	_, _, file := rmAccessOutput(t)
	cases := []struct {
		reader, attr, want string
	}{
		{"singleComposition", "context", "return x.Context, x.Context != nil, true"},
		{"singleComposition", "composer", "return x.Composer, x.Composer != nil && !rm.IsTypedNil(x.Composer), true"},
		{"singleComposition", "archetype_node_id", `return x.ArchetypeNodeID, x.ArchetypeNodeID != "", true`},
		{"singleDVCount", "magnitude", "return x.Magnitude, true, true"},
		{"singleEHRStatus", "is_modifiable", "return x.IsModifiable, true, true"},
		{"singleComposition", "name", "return x.Name, presentText(x.Name), true"},
		{"singleComposition", "category", "return x.Category, presentCodedText(x.Category), true"},
		{"singleComposition", "language", "return x.Language, presentCodePhrase(x.Language), true"},
		{"singleRole", "performer", "return x.Performer, presentPartyRef(x.Performer), true"},
		{"singleEventContext", "start_time", "return x.StartTime, !isZeroDVDateTime(x.StartTime), true"},
		{"singleObservation", "data", "return x.Data, !isZeroHistoryItemStructure(x.Data), true"},
		{"singleDVIntervalDVQuantity", "lower", "return x.Lower, presentIntervalBound(x.LowerUnbounded, x.Lower), true"},
		{"singleDVIntervalDVOrdered", "upper", "return x.Upper, presentIntervalBound(x.UpperUnbounded, x.Upper), true"},
		{"singleEHRStatus", "subject", "return x.Subject, presentEHRStatusSubject(x.Subject), true"},
		{"singleArchetyped", "archetype_id", "return x.ArchetypeID, presentArchetypedID(x.ArchetypeID), true"},
		{"singleArchetyped", "rm_version", "return x.RMVersion, presentArchetypedRMVersion(x.RMVersion), true"},
		{"singleItemSingle", "item", "return &x.Item, !isZeroElement(x.Item), true"},
		{"singleReferenceRangeDVQuantity", "range", "return &x.Range, !isZeroDVIntervalDVOrdered(x.Range), true"},
		{"singleIsmTransition", "careflow_step", "if x.CareflowStep == nil {\n\treturn nil, false, true\n}\nreturn *x.CareflowStep, true, true"},
		{"singleDVProportion", "precision", "if x.Precision == nil {\n\treturn nil, false, true\n}\nreturn *x.Precision, true, true"},
		{"singleCodePhrase", "terminology_id", "return x.TerminologyID.Value, !isZeroTerminologyID(x.TerminologyID), true"},
		{"multipleComposition", "content", "return boxValues(x.Content), x.Content != nil, true"},
		{"multipleItemList", "items", "return boxPointers(x.Items), x.Items != nil, true"},
	}
	for _, tc := range cases {
		t.Run(tc.reader+"/"+tc.attr, func(t *testing.T) {
			fd := funcDecl(file, tc.reader)
			if fd == nil {
				t.Fatalf("rendered file has no %s", tc.reader)
			}
			got, ok := caseBodies(t, fd)[tc.attr]
			if !ok {
				t.Fatalf("%s has no case %q", tc.reader, tc.attr)
			}
			if strings.TrimSpace(got) != tc.want {
				t.Errorf("%s case %q:\n%s\nwant:\n%s", tc.reader, tc.attr, strings.TrimSpace(got), tc.want)
			}
		})
	}
}

// rmStructFields reads the struct declarations of the generated RM package
// from source and returns, per type name, its field names, an embedded field
// by the name of its type. It is a source independent of the generator's
// plan, so a zero test that skips a field is caught against the struct
// itself.
func rmStructFields(t *testing.T) map[string][]string {
	t.Helper()
	paths, err := filepath.Glob("../../openehr/rm/*_gen.go")
	if err != nil || len(paths) == 0 {
		t.Fatalf("list openehr/rm/*_gen.go: %d files, %v", len(paths), err)
	}
	out := map[string][]string{}
	for _, path := range paths {
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			t.Fatalf("parse %s: %v", path, err)
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				if st, ok := ts.Type.(*ast.StructType); ok {
					out[ts.Name.Name] = structFieldNames(st)
				}
			}
		}
	}
	return out
}

// structFieldNames returns the field names of st, an embedded field by the
// name of its type.
func structFieldNames(st *ast.StructType) []string {
	var names []string
	for _, field := range st.Fields.List {
		if len(field.Names) == 0 {
			names = append(names, types.ExprString(genericBase(field.Type)))
			continue
		}
		for _, n := range field.Names {
			names = append(names, n.Name)
		}
	}
	return names
}

// genericBase strips the type arguments off an instantiated type expression.
func genericBase(e ast.Expr) ast.Expr {
	switch ix := e.(type) {
	case *ast.IndexExpr:
		return ix.X
	case *ast.IndexListExpr:
		return ix.X
	}
	return e
}

// TestRenderRMAccessFile_REQ171_ZeroTestsReadEveryField pins that a
// generated zero test compares every field of the Go struct it tests, its
// embedded structs included, so a value with any one field set is not read
// as zero.
func TestRenderRMAccessFile_REQ171_ZeroTestsReadEveryField(t *testing.T) {
	_, _, file := rmAccessOutput(t)
	structs := rmStructFields(t)
	tests := 0
	for _, d := range file.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || !strings.HasPrefix(fd.Name.Name, "isZero") {
			continue
		}
		tests++
		param := fd.Type.Params.List[0]
		sel, ok := genericBase(param.Type).(*ast.SelectorExpr)
		if !ok {
			t.Errorf("%s tests a %s, want an rm type", fd.Name.Name, types.ExprString(param.Type))
			continue
		}
		want, ok := structs[sel.Sel.Name]
		if !ok {
			t.Errorf("%s tests rm.%s, which openehr/rm does not declare as a struct", fd.Name.Name, sel.Sel.Name)
			continue
		}
		read := map[string]bool{}
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			if se, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := se.X.(*ast.Ident); ok && id.Name == param.Names[0].Name {
					read[se.Sel.Name] = true
				}
			}
			return true
		})
		got := slices.Sorted(maps.Keys(read))
		if !slices.Equal(got, slices.Sorted(slices.Values(want))) {
			t.Errorf("%s reads the fields %q of rm.%s, want every field %q", fd.Name.Name, got, sel.Sel.Name, slices.Sorted(slices.Values(want)))
		}
	}
	if tests < 10 {
		t.Fatalf("found %d zero tests, want one per class an attribute holds by value", tests)
	}
}

// TestParseGoType_REQ171 pins the parser the access reads field types with,
// on the shapes the struct renderer writes.
func TestParseGoType_REQ171(t *testing.T) {
	cases := []struct {
		in, qualified string
		kind          goTypeKind
	}{
		{"DVTextLike", "rm.DVTextLike", goNamed},
		{"*DVDuration", "*rm.DVDuration", goPointer},
		{"[]Event", "[]rm.Event", goSlice},
		{"map[string]ResourceDescriptionItem", "map[string]rm.ResourceDescriptionItem", goMap},
		{"*map[string]string", "*map[string]string", goPointer},
		{"History[ItemStructure]", "rm.History[rm.ItemStructure]", goNamed},
		{"OriginalVersion[any]", "rm.OriginalVersion[any]", goNamed},
		{"any /* TODO: unmapped Env */", "any", goNamed},
	}
	for _, tc := range cases {
		got, err := parseGoType(tc.in)
		if err != nil {
			t.Errorf("parseGoType(%q): %v", tc.in, err)
			continue
		}
		if got.kind != tc.kind || got.qualified() != tc.qualified {
			t.Errorf("parseGoType(%q) = kind %d %s, want kind %d %s", tc.in, got.kind, got.qualified(), tc.kind, tc.qualified)
		}
	}
	for _, bad := range []string{"", "map[string", "Foo[A", "Foo[A]x", "rm.Foo"} {
		if _, err := parseGoType(bad); err == nil {
			t.Errorf("parseGoType(%q) = nil error, want a refusal", bad)
		}
	}
	bound := mustParseGoType(t, "*T").bind(map[string]*goType{"T": mustParseGoType(t, "DVQuantity")})
	if bound.qualified() != "*rm.DVQuantity" {
		t.Errorf("bind(*T, T=DVQuantity) = %s, want *rm.DVQuantity", bound.qualified())
	}
}

func mustParseGoType(t *testing.T, s string) *goType {
	t.Helper()
	g, err := parseGoType(s)
	if err != nil {
		t.Fatalf("parseGoType(%q): %v", s, err)
	}
	return g
}
