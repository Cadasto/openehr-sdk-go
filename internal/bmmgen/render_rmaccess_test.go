// TestRenderRMAccessFile_REQ171_Deterministic pins that the output is
// gofmt'd and byte-identical across runs.
func TestRenderRMAccessFile_REQ171_Deterministic(t *testing.T) {
	plan, out, _ := rmAccessOutput(t)
	again, err := RenderRMAccessFile(plan)
	if err != nil {
		t.Fatalf("RenderRMAccessFile(RM) second run: %v", err)
	}
	if !bytes.Equal(out, again) {
		t.Error("RenderRMAccessFile(RM) differs between two runs on one plan")
	}
	formatted, err := format.Source(out)
	if err != nil || !bytes.Equal(formatted, out) {
		t.Errorf("RenderRMAccessFile(RM) output is not gofmt'd (format error %v)", err)
	}
	if !bytes.HasPrefix(out, []byte("// Code generated by bmmgen; DO NOT EDIT.\n")) {
		t.Error("RenderRMAccessFile(RM) output lacks the generated-code header")
	}
}

// TestRenderRMAccessFile_REQ171_CoversTheRegistry pins that covers lists, in
// pointer and value form, exactly the Go types the reverse registry
// recognises for the classes the type registry decodes, and that every arm's
// readers answer exactly the attributes the class declares (the fold rminfo
// is generated from), containers through multiple and every other attribute
// through single, and every Hash attribute through hash as well.
func TestRenderRMAccessFile_REQ171_CoversTheRegistry(t *testing.T) {
	plan, _, file := rmAccessOutput(t)

	type armWant struct {
		suffix string
		single []string
		multi  []string
		hash   []string
	}
	want := map[string]bool{}
	var arms []armWant
	for _, pc := range plan.ConcreteClasses {
		names, err := reverseRegistryArms(plan, pc)
		if err != nil {
			t.Fatalf("reverseRegistryArms(%s): %v", pc.BMMName, err)
		}
		attrs, _ := effectiveProperties(plan, pc.BMMName)
		var single, multi, hash []string
		for _, name := range sortedStringKeys(attrs) {
			if attrs[name].container {
				multi = append(multi, name)
			} else {
				single = append(single, name)
			}
			if attrs[name].typeName == "Hash" {
				hash = append(hash, name)
			}
		}
		for _, arm := range names {
			typ, err := parseGoType(arm)
			if err != nil {
				t.Fatalf("parseGoType(%q): %v", arm, err)
			}
			want[typ.qualified()] = true
			want["*"+typ.qualified()] = true
			arms = append(arms, armWant{suffix: typ.suffix(), single: single, multi: multi, hash: hash})
		}
	}
	if len(plan.ConcreteClasses) < 100 || len(arms) <= len(plan.ConcreteClasses) {
		t.Fatalf("%d concrete classes and %d arms, want the full RM registry with its generic instantiations", len(plan.ConcreteClasses), len(arms))
	}

	covers := funcDecl(file, "covers")
	if covers == nil {
		t.Fatal("rendered file has no covers function")
	}
	got := map[string]bool{}
	ast.Inspect(covers, func(n ast.Node) bool {
		if cc, ok := n.(*ast.CaseClause); ok {
			for _, e := range cc.List {
				got[types.ExprString(e)] = true
			}
		}
		return true
	})
	for _, typ := range slices.Sorted(maps.Keys(want)) {
		if !got[typ] {
			t.Errorf("covers does not list %s, which the registry recognises", typ)
		}
	}
	for _, typ := range slices.Sorted(maps.Keys(got)) {
		if !want[typ] {
			t.Errorf("covers lists %s, which the registry does not recognise", typ)
		}
	}

	for _, arm := range arms {
		for _, reader := range []struct {
			prefix string
			attrs  []string
		}{{"single", arm.single}, {"multiple", arm.multi}, {"hash", arm.hash}} {
			fd := funcDecl(file, reader.prefix+arm.suffix)
			if fd == nil {
				if len(reader.attrs) > 0 {
					t.Errorf("no %s%s for the attributes %q", reader.prefix, arm.suffix, reader.attrs)
				}
				continue
			}
			got := slices.Sorted(maps.Keys(caseBodies(t, fd)))
			if !slices.Equal(got, reader.attrs) {
				t.Errorf("%s%s answers %q, want %q", reader.prefix, arm.suffix, got, reader.attrs)
			}
		}
	}
}

