// TestRMAccessGen_REQ171_Refusals pins that the generator refuses what it
// cannot read rather than emit a wrong reader: a shape on a field of the
// wrong kind, a shape it does not know, a container held as a Go map, a
// Hash attribute not held as a map keyed by string, and a Go map on an
// attribute not declared Hash.
func TestRMAccessGen_REQ171_Refusals(t *testing.T) {
	plan, _, _ := rmAccessOutput(t)
	shapes := []struct {
		name    string
		shapes  map[string]map[string]accessShape
		wantErr string
	}{
		{name: "address of a pointer field", shapes: map[string]map[string]accessShape{"COMPOSITION": {"context": shapeAddress}}, wantErr: "COMPOSITION.context is handed back by address, but its field is not held by value"},
		{name: "dereference of a value field", shapes: map[string]map[string]accessShape{"COMPOSITION": {"category": shapeDeref}}, wantErr: "COMPOSITION.category is handed back dereferenced, but its field is not a pointer"},
		{name: "value member of a string field", shapes: map[string]map[string]accessShape{"COMPOSITION": {"archetype_node_id": shapeValueMember}}, wantErr: "COMPOSITION.archetype_node_id is handed back as its value member, but its field is not held by value"},
		{name: "a shape the generator does not know", shapes: map[string]map[string]accessShape{"COMPOSITION": {"name": accessShape(99)}}, wantErr: "COMPOSITION.name has shape 99, which the generator does not know"},
	}
	for _, tc := range shapes {
		t.Run(tc.name, func(t *testing.T) {
			g, err := newRMAccessGen(plan)
			if err != nil {
				t.Fatalf("newRMAccessGen: %v", err)
			}
			g.shapes = tc.shapes
			if _, err := g.render(); err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Errorf("render with shapes %v = %v, want an error containing %q", tc.shapes, err, tc.wantErr)
			}
		})
	}

	g, err := newRMAccessGen(plan)
	if err != nil {
		t.Fatalf("newRMAccessGen: %v", err)
	}
	var arm *accessArm
	for _, pc := range plan.ConcreteClasses {
		if pc.BMMName == "RESOURCE_DESCRIPTION" {
			arms, err := g.arms(pc)
			if err != nil {
				t.Fatalf("arms(RESOURCE_DESCRIPTION): %v", err)
			}
			arm = arms[0]
		}
	}
	if arm == nil {
		t.Fatal("no RESOURCE_DESCRIPTION among the concrete classes")
	}
	attr := func(declared string, container bool, typ string) *accessAttr {
		gt := mustParseGoType(t, typ)
		kind, err := g.classify(gt)
		if err != nil {
			t.Fatalf("classify(%s): %v", typ, err)
		}
		return &accessAttr{name: "doctored", field: "Doctored", declared: declared, container: container, typ: gt, kind: kind}
	}
	attrs := []struct {
		name    string
		attr    *accessAttr
		wantErr string
	}{
		{name: "container held as a map", attr: attr("RESOURCE_DESCRIPTION_ITEM", true, "map[string]ResourceDescriptionItem"), wantErr: "container RESOURCE_DESCRIPTION.doctored has Go type map[string]rm.ResourceDescriptionItem, not a slice"},
		{name: "Hash held as a slice", attr: attr("Hash", false, "[]string"), wantErr: "Hash RESOURCE_DESCRIPTION.doctored has Go type []string, not a map keyed by string"},
		{name: "Hash keyed by a number", attr: attr("Hash", false, "map[int]string"), wantErr: "Hash RESOURCE_DESCRIPTION.doctored has Go type map[int]string, not a map keyed by string"},
		{name: "map not declared Hash", attr: attr("String", false, "map[string]string"), wantErr: "RESOURCE_DESCRIPTION.doctored is declared String, but its Go type map[string]string is a map"},
		{name: "pointer to a map not declared Hash", attr: attr("String", false, "*map[string]string"), wantErr: "RESOURCE_DESCRIPTION.doctored is declared String, but its Go type *map[string]string is a map"},
	}
	for _, tc := range attrs {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := g.split(arm, []*accessAttr{tc.attr}); err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Errorf("split(%s: %s %s) = %v, want an error containing %q", tc.attr.name, tc.attr.declared, tc.attr.typ.qualified(), err, tc.wantErr)
			}
		})
	}
}

// rmStructFields reads the struct declarations of the generated RM package
// from source and returns, per type name, its field names, an embedded field
// by the name of its type. It is a source independent of the generator's
// plan, so a zero test that skips a field is caught against the struct
// itself.
func rmStructFields(t *testing.T) map[string][]string {
	t.Helper()
	paths, err := filepath.Glob("../../openehr/rm/*_gen.go")
	if err != nil || len(paths) == 0 {
		t.Fatalf("list openehr/rm/*_gen.go: %d files, %v", len(paths), err)
	}
	out := map[string][]string{}
	for _, path := range paths {
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			t.Fatalf("parse %s: %v", path, err)
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				if st, ok := ts.Type.(*ast.StructType); ok {
					out[ts.Name.Name] = structFieldNames(st)
				}
			}
		}
	}
	return out
}

// structFieldNames returns the field names of st, an embedded field by the
// name of its type.
func structFieldNames(st *ast.StructType) []string {
	var names []string
	for _, field := range st.Fields.List {
		if len(field.Names) == 0 {
			names = append(names, types.ExprString(genericBase(field.Type)))
			continue
		}
		for _, n := range field.Names {
			names = append(names, n.Name)
		}
	}
	return names
}

// genericBase strips the type arguments off an instantiated type expression.
func genericBase(e ast.Expr) ast.Expr {
	switch ix := e.(type) {
	case *ast.IndexExpr:
		return ix.X
	case *ast.IndexListExpr:
		return ix.X
	}
	return e
}

// TestRenderRMAccessFile_REQ171_ZeroTestsReadEveryField pins that a
// generated zero test compares every field of the Go struct it tests, its
// embedded structs included, so a value with any one field set is not read
// as zero.
func TestRenderRMAccessFile_REQ171_ZeroTestsReadEveryField(t *testing.T) {
	_, _, file := rmAccessOutput(t)
	structs := rmStructFields(t)
	tests := 0
	for _, d := range file.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || !strings.HasPrefix(fd.Name.Name, "isZero") {
			continue
		}
		tests++
		param := fd.Type.Params.List[0]
		sel, ok := genericBase(param.Type).(*ast.SelectorExpr)
		if !ok {
			t.Errorf("%s tests a %s, want an rm type", fd.Name.Name, types.ExprString(param.Type))
			continue
		}
		want, ok := structs[sel.Sel.Name]
		if !ok {
			t.Errorf("%s tests rm.%s, which openehr/rm does not declare as a struct", fd.Name.Name, sel.Sel.Name)
			continue
		}
		read := map[string]bool{}
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			if se, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := se.X.(*ast.Ident); ok && id.Name == param.Names[0].Name {
					read[se.Sel.Name] = true
				}
			}
			return true
		})
		got := slices.Sorted(maps.Keys(read))
		if !slices.Equal(got, slices.Sorted(slices.Values(want))) {
			t.Errorf("%s reads the fields %q of rm.%s, want every field %q", fd.Name.Name, got, sel.Sel.Name, slices.Sorted(slices.Values(want)))
		}
	}
	if tests < 10 {
		t.Fatalf("found %d zero tests, want one per class an attribute holds by value", tests)
	}
}

// TestParseGoType_REQ171 pins the parser the access reads field types with,
// on the shapes the struct renderer writes.
func TestParseGoType_REQ171(t *testing.T) {
	cases := []struct {
		in, qualified string
		kind          goTypeKind
	}{
		{"DVTextLike", "rm.DVTextLike", goNamed},
		{"*DVDuration", "*rm.DVDuration", goPointer},
		{"[]Event", "[]rm.Event", goSlice},
		{"map[string]ResourceDescriptionItem", "map[string]rm.ResourceDescriptionItem", goMap},
		{"*map[string]string", "*map[string]string", goPointer},
		{"History[ItemStructure]", "rm.History[rm.ItemStructure]", goNamed},
		{"OriginalVersion[any]", "rm.OriginalVersion[any]", goNamed},
		{"any /* TODO: unmapped Env */", "any", goNamed},
	}
	for _, tc := range cases {
		got, err := parseGoType(tc.in)
		if err != nil {
			t.Errorf("parseGoType(%q): %v", tc.in, err)
			continue
		}
		if got.kind != tc.kind || got.qualified() != tc.qualified {
			t.Errorf("parseGoType(%q) = kind %d %s, want kind %d %s", tc.in, got.kind, got.qualified(), tc.kind, tc.qualified)
		}
	}
	for _, bad := range []string{"", "map[string", "Foo[A", "Foo[A]x", "rm.Foo"} {
		if _, err := parseGoType(bad); err == nil {
			t.Errorf("parseGoType(%q) = nil error, want a refusal", bad)
		}
	}
	bound := mustParseGoType(t, "*T").bind(map[string]*goType{"T": mustParseGoType(t, "DVQuantity")})
	if bound.qualified() != "*rm.DVQuantity" {
		t.Errorf("bind(*T, T=DVQuantity) = %s, want *rm.DVQuantity", bound.qualified())
	}
}

func mustParseGoType(t *testing.T, s string) *goType {
	t.Helper()
	g, err := parseGoType(s)
	if err != nil {
		t.Fatalf("parseGoType(%q): %v", s, err)
	}
	return g
}
