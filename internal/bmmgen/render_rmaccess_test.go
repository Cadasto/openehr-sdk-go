// rmAccessOutput renders the access file for the pinned RM schemas and
// parses it.
func rmAccessOutput(t *testing.T) (*Plan, []byte, *ast.File) {
	t.Helper()
	plan, err := BuildPlanForTarget(context.Background(), TargetRM, bmm.FSResolver{Root: testResources})
	if err != nil {
		t.Fatalf("BuildPlanForTarget(RM): %v", err)
	}
	out, err := RenderRMAccessFile(plan)
	if err != nil {
		t.Fatalf("RenderRMAccessFile(RM): %v", err)
	}
	file, err := parser.ParseFile(token.NewFileSet(), rmaccessFile, out, 0)
	if err != nil {
		t.Fatalf("parse rendered %s: %v", rmaccessFile, err)
	}
	return plan, out, file
}

// funcDecl returns the top-level function name of file, or nil.
func funcDecl(file *ast.File, name string) *ast.FuncDecl {
	for _, d := range file.Decls {
		if fd, ok := d.(*ast.FuncDecl); ok && fd.Name.Name == name {
			return fd
		}
	}
	return nil
}

// caseBodies returns, for the attribute switch of a generated reader, the
// source of each case's body keyed by the attribute name it matches.
func caseBodies(t *testing.T, fd *ast.FuncDecl) map[string]string {
	t.Helper()
	out := map[string]string{}
	ast.Inspect(fd, func(n ast.Node) bool {
		cc, ok := n.(*ast.CaseClause)
		if !ok || len(cc.List) != 1 {
			return true
		}
		lit, ok := cc.List[0].(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			return true
		}
		name, err := strconv.Unquote(lit.Value)
		if err != nil {
			t.Fatalf("%s: case %s: %v", fd.Name.Name, lit.Value, err)
		}
		var b bytes.Buffer
		for _, stmt := range cc.Body {
			if err := printer.Fprint(&b, token.NewFileSet(), stmt); err != nil {
				t.Fatalf("print %s case %q: %v", fd.Name.Name, name, err)
			}
			b.WriteString("\n")
		}
		out[name] = b.String()
		return true
	})
	return out
}

