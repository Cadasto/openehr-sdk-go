// TestREQ042_RunEmitsReleaseFile — the generator run writes the release file into
// the RM package and nowhere else, and verify mode checks it for drift.
func TestREQ042_RunEmitsReleaseFile(t *testing.T) {
	out := t.TempDir()
	res, err := Run(Options{ResourcesDir: testResources, OutDir: out})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	want := filepath.Join(out, TargetRM.OutSubDir, releaseFileName)
	var found int
	for _, f := range res.Files {
		if filepath.Base(f) == releaseFileName {
			found++
			if f != want {
				t.Errorf("release file written at %s, want %s", f, want)
			}
		}
	}
	if found != 1 {
		t.Fatalf("Run wrote %d release files, want 1", found)
	}
	body, err := os.ReadFile(want)
	if err != nil {
		t.Fatalf("read %s: %v", want, err)
	}
	if got, ok := releaseConst(t, body); !ok || got != schemaRMRelease(t, TargetRM.RootID) {
		t.Errorf("written Release = %q (declared %t), want the schema's rm_release", got, ok)
	}

	if err := os.WriteFile(want, []byte("package rm\n"), 0o644); err != nil {
		t.Fatalf("tamper %s: %v", want, err)
	}
	vres, err := Run(Options{ResourcesDir: testResources, OutDir: out, Verify: true})
	if err != nil {
		t.Fatalf("Run(verify): %v", err)
	}
	var drifted bool
	for _, d := range vres.Drifts {
		drifted = drifted || d.Path == want
	}
	if !drifted {
		t.Errorf("verify mode did not report drift on a hand-edited %s", releaseFileName)
	}
}

// TestCheckFixedNameCollisions pins which file stems the generator reserves
// for its own fixed-name files: a BMM package whose file would be written over
// by typereg_gen.go, jsonhooks_gen.go, interval_bound_gen.go or
// release_gen.go is refused, the error names both files, and an ordinary plan
// passes.
func TestCheckFixedNameCollisions(t *testing.T) {
	for _, tc := range []struct {
		fileBase string
		fixed    string
	}{
		{"typereg", "typereg_gen.go"},
		{"jsonhooks", "jsonhooks_gen.go"},
		{"interval_bound", intervalBoundFile},
		{"release", releaseFileName},
	} {
		t.Run(tc.fixed, func(t *testing.T) {
			plan := &Plan{Files: []*PlannedFile{{FileBase: "data_types_quantity"}, {FileBase: tc.fileBase}}}
			err := checkFixedNameCollisions(plan)
			if err == nil {
				t.Fatalf("checkFixedNameCollisions with a BMM package file %q = nil, want a collision with %s", tc.fileBase, tc.fixed)
			}
			for _, want := range []string{tc.fileBase, tc.fixed} {
				if !strings.Contains(err.Error(), want) {
					t.Errorf("collision error %q does not name %q", err, want)
				}
			}
		})
	}

	if err := checkFixedNameCollisions(&Plan{Files: []*PlannedFile{{FileBase: "interval_bound_extra"}, {FileBase: "release_notes"}}}); err != nil {
		t.Errorf("checkFixedNameCollisions with stems that only start like a fixed name = %v, want nil", err)
	}
}

// TestRunRefusesBMMPackageNamedLikeAFixedFile pins that a generator run stops
// before writing anything when a BMM package would take the name of one of its
// fixed-name files. The test renames the RM schema's single-class
// `integration` package, so the collision comes from the schema, not from a
// hand-built plan.
func TestRunRefusesBMMPackageNamedLikeAFixedFile(t *testing.T) {
	entries, err := os.ReadDir(testResources)
	if err != nil {
		t.Fatalf("read %s: %v", testResources, err)
	}
	for _, tc := range []struct {
		pkg   string
		fixed string
	}{
		{"typereg", "typereg_gen.go"},
		{"jsonhooks", "jsonhooks_gen.go"},
		{"interval_bound", intervalBoundFile},
		{"release", releaseFileName},
	} {
		t.Run(tc.fixed, func(t *testing.T) {
			resources := t.TempDir()
			for _, e := range entries {
				if e.IsDir() {
					continue
				}
				body, err := os.ReadFile(filepath.Join(testResources, e.Name()))
				if err != nil {
					t.Fatalf("read %s: %v", e.Name(), err)
				}
				if e.Name() == "openehr_rm_1.2.0.bmm.json" {
					renamed := strings.ReplaceAll(string(body), `"org.openehr.rm.integration"`, `"org.openehr.rm.`+tc.pkg+`"`)
					if renamed == string(body) {
						t.Fatal("the RM schema no longer declares the package org.openehr.rm.integration")
					}
					body = []byte(renamed)
				}
				if err := os.WriteFile(filepath.Join(resources, e.Name()), body, 0o600); err != nil {
					t.Fatalf("write %s: %v", e.Name(), err)
				}
			}

			out := t.TempDir()
			_, err := Run(Options{ResourcesDir: resources, OutDir: out})
			if err == nil {
				t.Fatalf("Run with a BMM package %q = nil error, want a collision with %s", tc.pkg, tc.fixed)
			}
			if want := "collides with " + tc.fixed; !strings.Contains(err.Error(), want) {
				t.Errorf("Run error = %q, want it to contain %q", err, want)
			}
			if _, statErr := os.Stat(filepath.Join(out, TargetRM.OutSubDir)); statErr == nil {
				t.Errorf("Run wrote into %s before refusing the collision", TargetRM.OutSubDir)
			}
		})
	}
}

// TestRunRefusesFixedFileNameInAnyTarget pins that the reservation of the
// generator's fixed-name files is uniform: a BMM package of the AOM 1.4 target
// named like a fixed file is refused, including the two names that target
// never emits (interval_bound_gen.go and release_gen.go). Guarding the check
// with the RM target alone would let those two through. The test renames the
// AOM schema's `openehr_archetype_profile` package and runs the AOM target
// alone, so the RM target cannot be the one that refuses.
func TestRunRefusesFixedFileNameInAnyTarget(t *testing.T) {
	entries, err := os.ReadDir(testResources)
	if err != nil {
		t.Fatalf("read %s: %v", testResources, err)
	}
	for _, tc := range []struct {
		pkg   string
		fixed string
	}{
		{"typereg", "typereg_gen.go"},
		{"jsonhooks", "jsonhooks_gen.go"},
		{"interval_bound", intervalBoundFile},
		{"release", releaseFileName},
	} {
		t.Run(tc.fixed, func(t *testing.T) {
			resources := t.TempDir()
			for _, e := range entries {
				if e.IsDir() {
					continue
				}
				body, err := os.ReadFile(filepath.Join(testResources, e.Name()))
				if err != nil {
					t.Fatalf("read %s: %v", e.Name(), err)
				}
				if e.Name() == "openehr_am_1.4.0.bmm.json" {
					renamed := strings.ReplaceAll(string(body), "openehr_archetype_profile", tc.pkg)
					if renamed == string(body) {
						t.Fatal("the AOM 1.4 schema no longer declares the package openehr_archetype_profile")
					}
					body = []byte(renamed)
				}
				if err := os.WriteFile(filepath.Join(resources, e.Name()), body, 0o600); err != nil {
					t.Fatalf("write %s: %v", e.Name(), err)
				}
			}

			out := t.TempDir()
			_, err := Run(Options{ResourcesDir: resources, OutDir: out, Targets: []Target{TargetAOM14}})
			if err == nil {
				t.Fatalf("Run on the AOM 1.4 target with a BMM package %q = nil error, want a collision with %s", tc.pkg, tc.fixed)
			}
			if want := "collides with " + tc.fixed; !strings.Contains(err.Error(), want) {
				t.Errorf("Run error = %q, want it to contain %q", err, want)
			}
			if _, statErr := os.Stat(filepath.Join(out, TargetAOM14.OutSubDir)); statErr == nil {
				t.Errorf("Run wrote into %s before refusing the collision", TargetAOM14.OutSubDir)
			}
		})
	}
}
