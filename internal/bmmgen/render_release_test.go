package bmmgen

// REQ-041 / REQ-042 / REQ-044 — rm.Release is generated from the primary RM
// schema's rm_release, drift-checked by verify mode, and never hand-written.

import (
	"context"
	"encoding/json"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"

	"github.com/cadasto/openehr-sdk-go/openehr/bmm"
)

// schemaRMRelease reads rm_release straight from the pinned schema file, so
// the expected value does not pass through the loader the generator uses.
func schemaRMRelease(t *testing.T, rootID string) string {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(testResources, rootID+".bmm.json"))
	if err != nil {
		t.Fatalf("read %s: %v", rootID, err)
	}
	var doc struct {
		RMRelease string `json:"rm_release"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("decode %s: %v", rootID, err)
	}
	if doc.RMRelease == "" {
		t.Fatalf("%s declares no rm_release", rootID)
	}
	return doc.RMRelease
}

// releaseConst parses a rendered file and returns the value of its exported
// constant Release, or ok=false when the file declares none.
func releaseConst(t *testing.T, src []byte) (value string, ok bool) {
	t.Helper()
	f, err := parser.ParseFile(token.NewFileSet(), releaseFileName, src, 0)
	if err != nil {
		t.Fatalf("parse rendered %s: %v", releaseFileName, err)
	}
	for _, decl := range f.Decls {
		gd, isGen := decl.(*ast.GenDecl)
		if !isGen || gd.Tok != token.CONST {
			continue
		}
		for _, spec := range gd.Specs {
			vs, isValue := spec.(*ast.ValueSpec)
			if !isValue || len(vs.Names) != 1 || vs.Names[0].Name != "Release" || len(vs.Values) != 1 {
				continue
			}
			lit, isLit := vs.Values[0].(*ast.BasicLit)
			if !isLit || lit.Kind != token.STRING {
				t.Fatalf("Release is not a string literal: %#v", vs.Values[0])
			}
			v, err := strconv.Unquote(lit.Value)
			if err != nil {
				t.Fatalf("unquote Release %s: %v", lit.Value, err)
			}
			return v, true
		}
	}
	return "", false
}

// TestREQ041_RenderReleaseFileEmitsSchemaRMRelease — REQ-041 / REQ-044: the constant
// the SDK writes into ARCHETYPED.rm_version is generated from the primary RM
// schema's rm_release, in package rm, under the standard generated header.
func TestREQ041_RenderReleaseFileEmitsSchemaRMRelease(t *testing.T) {
	plan, err := BuildPlanForTarget(context.Background(), TargetRM, bmm.FSResolver{Root: testResources})
	if err != nil {
		t.Fatalf("BuildPlanForTarget(RM): %v", err)
	}
	body, err := RenderReleaseFile(plan)
	if err != nil {
		t.Fatalf("RenderReleaseFile(RM): %v", err)
	}
	if body == nil {
		t.Fatal("RenderReleaseFile(RM) emitted nothing")
	}

	want := schemaRMRelease(t, TargetRM.RootID)
	got, ok := releaseConst(t, body)
	if !ok {
		t.Fatalf("rendered %s declares no const Release:\n%s", releaseFileName, body)
	}
	if got != want {
		t.Errorf("rendered Release = %q, want the schema's rm_release %q", got, want)
	}

	src := string(body)
	for _, line := range []string{
		"// Code generated by bmmgen; DO NOT EDIT.\n",
		"// Source: " + TargetRM.SourceLabel + "\n",
		"package rm\n",
	} {
		if !strings.Contains(src, line) {
			t.Errorf("rendered %s lacks %q", releaseFileName, line)
		}
	}
	if strings.Contains(src, "REQ-") {
		t.Errorf("rendered %s carries a requirement id in its doc comment", releaseFileName)
	}
}

// TestREQ041_RenderReleaseFileFollowsTheSchema — the value is read from the schema,
// not written into the generator: a bumped rm_release changes the constant.
func TestREQ041_RenderReleaseFileFollowsTheSchema(t *testing.T) {
	plan := &Plan{Target: TargetRM, Schema: &bmm.Schema{RMRelease: "9.8.7"}}
	body, err := RenderReleaseFile(plan)
	if err != nil {
		t.Fatalf("RenderReleaseFile: %v", err)
	}
	if got, ok := releaseConst(t, body); !ok || got != "9.8.7" {
		t.Errorf("rendered Release = %q (declared %t), want %q", got, ok, "9.8.7")
	}
}

// TestREQ041_RenderReleaseFileRefusesAnEmptyRelease — an empty constant would write
// an ARCHETYPED whose rm_version the RM floor rejects, so generation fails.
func TestREQ041_RenderReleaseFileRefusesAnEmptyRelease(t *testing.T) {
	for _, plan := range []*Plan{
		{Target: TargetRM, Schema: &bmm.Schema{}},
		{Target: TargetRM},
	} {
		if body, err := RenderReleaseFile(plan); err == nil {
			t.Errorf("RenderReleaseFile(schema %+v) = %d bytes, nil error; want an error", plan.Schema, len(body))
		}
	}
}

// TestREQ041_RenderReleaseFileSkipsNonRMTargets — the AOM 1.4 target has no RM
// release of its own, so it emits no release file.
func TestREQ041_RenderReleaseFileSkipsNonRMTargets(t *testing.T) {
	plan, err := BuildPlanForTarget(context.Background(), TargetAOM14, bmm.FSResolver{Root: testResources})
	if err != nil {
		t.Fatalf("BuildPlanForTarget(AOM14): %v", err)
	}
	body, err := RenderReleaseFile(plan)
	if err != nil {
		t.Fatalf("RenderReleaseFile(AOM14): %v", err)
	}
	if body != nil {
		t.Errorf("AOM 1.4 target emitted %d bytes of release data", len(body))
	}
}

// TestREQ042_RunEmitsReleaseFile — the generator run writes the release file into
// the RM package and nowhere else, and verify mode checks it for drift.
func TestREQ042_RunEmitsReleaseFile(t *testing.T) {
	out := t.TempDir()
	res, err := Run(Options{ResourcesDir: testResources, OutDir: out})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	want := filepath.Join(out, TargetRM.OutSubDir, releaseFileName)
	var found int
	for _, f := range res.Files {
		if filepath.Base(f) == releaseFileName {
			found++
			if f != want {
				t.Errorf("release file written at %s, want %s", f, want)
			}
		}
	}
	if found != 1 {
		t.Fatalf("Run wrote %d release files, want 1", found)
	}
	body, err := os.ReadFile(want)
	if err != nil {
		t.Fatalf("read %s: %v", want, err)
	}
	if got, ok := releaseConst(t, body); !ok || got != schemaRMRelease(t, TargetRM.RootID) {
		t.Errorf("written Release = %q (declared %t), want the schema's rm_release", got, ok)
	}

	if err := os.WriteFile(want, []byte("package rm\n"), 0o644); err != nil {
		t.Fatalf("tamper %s: %v", want, err)
	}
	vres, err := Run(Options{ResourcesDir: testResources, OutDir: out, Verify: true})
	if err != nil {
		t.Fatalf("Run(verify): %v", err)
	}
	var drifted bool
	for _, d := range vres.Drifts {
		drifted = drifted || d.Path == want
	}
	if !drifted {
		t.Errorf("verify mode did not report drift on a hand-edited %s", releaseFileName)
	}
}
