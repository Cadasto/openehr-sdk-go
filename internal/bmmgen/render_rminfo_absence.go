package bmmgen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"

	"github.com/cadasto/openehr-sdk-go/openehr/bmm"
)

// absenceReason is the `rminfo.AbsenceReason` constant the generator renders
// for one declared-but-omitted class — the Go IDENTIFIER as a string, not a
// value of that type. bmmgen does not import rminfo, for the same reason
// [rmAttr] mirrors `rminfo.AttrMeta` by hand: the dependency stays one-way.
type absenceReason string

// The four reasons a DECLARED name can be out of the class universe, in
// REQ-049's fixed precedence order. The other two members of the enum are
// never generated: `AbsenceNone` means the name is IN the universe, and
// `AbsenceUndeclared` is computed by the accessor from the table's silence.
const (
	absencePrimitive       absenceReason = "AbsencePrimitive"
	absenceEnumeration     absenceReason = "AbsenceEnumeration"
	absenceExcludedClass   absenceReason = "AbsenceExcludedClass"
	absenceExcludedPackage absenceReason = "AbsenceExcludedPackage"
)

// absenceEntry is one row of the generated table: a declared class name and
// the single reason the class universe omits it.
type absenceEntry struct {
	className string
	reason    absenceReason
}

// RenderRMInfoAbsenceFile produces the `openehr/rm/rminfo/absence_gen.go`
// table from a planned RM emission: every name the target's pinned schemas
// declare that the class universe ([rmInfoUniverse]) omits, with the reason
// (REQ-049). It is the negative space behind REQ-048's membership answer,
// which the planner computes on every run and, before this table, discarded.
//
// Returns nil when the target is not the RM target, exactly as
// [RenderRMInfoFile] does — rminfo is generated alongside RM only.
//
// Returns an ERROR when a declared-but-omitted name matches no exclusion
// rule. That is deliberate: emitting nothing for such a name would have the
// accessor report it as *undeclared*, which is how a widened package skip
// could silently reclassify a real openEHR class as a name the schemas never
// mentioned.
//
// Output is deterministic: one entry per omitted name, sorted by class name.
func RenderRMInfoAbsenceFile(plan *Plan) ([]byte, error) {
	if plan.Target.GoPackage != "rm" {
		return nil, nil
	}
	entries, err := rmInfoAbsence(plan)
	if err != nil {
		return nil, err
	}

	var body bytes.Buffer
	body.WriteString("// Code generated by bmmgen; DO NOT EDIT.\n")
	fmt.Fprintf(&body, "// Source: %s\n\n", plan.Target.SourceLabel)
	body.WriteString("package rminfo\n\n")
	body.WriteString("// absenceData is the declared-but-omitted half of the class universe\n")
	body.WriteString("// (REQ-049): every name the pinned schemas declare that lookup_gen.go's\n")
	body.WriteString("// defaultData omits, with the one reason it is out. The two tables never\n")
	body.WriteString("// overlap, and no name outside the schemas appears here — undeclared is\n")
	body.WriteString("// computed from this table's silence, never stored in it.\n")
	body.WriteString("var absenceData = map[string]AbsenceReason{\n")
	for _, e := range entries {
		fmt.Fprintf(&body, "\t%q: %s,\n", e.className, e.reason)
	}
	body.WriteString("}\n")

	formatted, err := format.Source(body.Bytes())
	if err != nil {
		return body.Bytes(), fmt.Errorf("gofmt rminfo/absence_gen.go: %w", err)
	}
	return formatted, nil
}

// rmInfoAbsence accounts for every name the target's pinned schemas declare
// and the class universe omits, in class-name order.
//
// "Declared" is both declaration maps of the merged schema — `class_definitions`
// AND `primitive_types` — because a primitive is a declaration the universe
// omits on purpose, and a table that ignored it would call `Interval`
// undeclared.
func rmInfoAbsence(plan *Plan) ([]absenceEntry, error) {
	// The other rminfo renderer reads only the planned classes, so a plan
	// built by hand without a schema works there. Here the DECLARATIONS are
	// the input, and a missing schema would silently reduce the table to
	// "nothing is declared" — say so instead.
	if plan.Schema == nil {
		return nil, errors.New("bmmgen: rminfo absence table: plan carries no schema")
	}

	universe := rmInfoUniverse(plan)
	inUniverse := make(map[string]bool, len(universe))
	for _, name := range universe {
		inUniverse[name] = true
	}

	declared := make(map[string]bool, len(plan.Schema.ClassDefinitions)+len(plan.Schema.PrimitiveTypes))
	for name := range plan.Schema.ClassDefinitions {
		declared[name] = true
	}
	for name := range plan.Schema.PrimitiveTypes {
		declared[name] = true
	}

	entries := make([]absenceEntry, 0, len(declared))
	for _, name := range sortedStringKeys(declared) {
		if inUniverse[name] {
			continue
		}
		reason, ok := absenceReasonFor(plan, name)
		if !ok {
			return nil, fmt.Errorf(
				"bmmgen: rminfo absence table: class %s (package %q) is declared by the pinned schemas, "+
					"omitted from the class universe, and matched by no exclusion rule — "+
					"account for it with a rule or a new reason before generating (REQ-049)",
				name, plan.ClassPackages[name])
		}
		entries = append(entries, absenceEntry{className: name, reason: reason})
	}
	return entries, nil
}

// absenceReasonFor reports why the class universe omits a DECLARED name, under
// REQ-049's fixed precedence: primitive, then enumeration, then excluded
// class, then excluded package. ok=false means no rule accounts for the name —
// the caller's cue to fail generation rather than emit.
//
// The order puts what a name IS ahead of why it was SKIPPED, so the reported
// reason does not depend on the generator's redundancy: [skippedClasses]
// deliberately restates several primitive_types names as belt and braces, and
// those names must still report *primitive*.
//
// The primitive rule reads the schema's own `primitive_types` map plus
// [primitiveGoType] ("declared as, or mapped to, a § Primitive type mapping
// entry"). It deliberately does NOT consult [isSkippedPrimitive]: that map
// groups the functional / builtins foundation CLASSES (TUPLE, FUNCTION, Env, …)
// in beside the real primitives for the generator's own skip convenience, and
// those names are not primitives — they are excluded classes, and the
// exclusion set is what must account for them.
func absenceReasonFor(plan *Plan, name string) (absenceReason, bool) {
	if _, isPrimitiveDecl := plan.Schema.PrimitiveTypes[name]; isPrimitiveDecl || isPrimitive(name) {
		return absencePrimitive, true
	}
	if cls, declared := plan.Schema.ClassDefinitions[name]; declared {
		if _, isEnum := cls.(*bmm.Enumeration); isEnum {
			return absenceEnumeration, true
		}
	}
	if isSkippedClass(name) {
		return absenceExcludedClass, true
	}
	if isSkippedPackage(plan.ClassPackages[name]) {
		return absenceExcludedPackage, true
	}
	return "", false
}
