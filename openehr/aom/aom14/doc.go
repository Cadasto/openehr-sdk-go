// Package aom14 holds Go types generated from the openEHR Archetype
// Object Model 1.4, in the form the AM Release-1.4 XML schemas give an
// ADL 1.4 operational template (BMM source: the SDK's
// openehr_operational_template_1.4.0 root over openehr_am_1.4.0.bmm.json,
// the RM and openehr_base_1.3.0.bmm.json).
//
// # Layout
//
// This package sits next to [openehr/rm], not under
// [openehr/template]: AOM is the model of an archetype, and templates
// consume archetypes (an OPT contains flattened archetype definitions).
// Template code imports this package but does not own it.
//
// # Base-type sharing with openehr/rm
//
// AOM 1.4 includes openehr_base_1.3.0 by reference, the same way RM
// does. The generator does not duplicate base classes here; instead,
// references to base and RM classes (e.g. ARCHETYPE_ID, HIER_OBJECT_ID,
// CODE_PHRASE) are emitted as rm.<GoName> with
// a one-way import on openehr/rm. This avoids binary bloat and keeps
// the rm.HierObjectID type identical when AOM-side code interoperates
// with RM-side code.
//
// The reverse direction (rm importing aom14) is prohibited; AOM
// types are never referenced from RM.
//
// # Type registry
//
// Concrete AOM classes register with the shared
// [openehr/rm/typereg].Default registry at package-init time. The
// _type discriminator strings are disjoint between RM and AOM
// (no DV_QUANTITY in AOM, no ARCHETYPE in RM), so the two models
// coexist in a single registry. The generator emits typereg_gen.go
// here for the AOM side.
//
// # Reading an operational template
//
// [ReadOperationalTemplate] reads an operational template from an
// untrusted source into the model, within a size and a nesting limit. It
// has two modes. The default mode reads what the deprecated template
// parser reads: shapes and values the AM Release-1.4 schemas do not allow,
// such as a constraint object with no type, a <children> typed with a
// primitive class, a real number written as Go reads one, an element in
// another namespace, or text before the root element, each read as that
// parser reads it. Given [canxml.WithStrict], the strict mode reads the
// document as the schemas write it: it refuses each of those shapes and
// values, and any content the model does not read, keeping only the
// readings the function lists for every mode, such as the v2 namespace the
// schemas declare. In both modes it refuses four readings of the parser:
// an integer the model's 32-bit Integer cannot hold, an integer bound of
// positive infinity on the lower side or of negative infinity on the upper
// one, which admits no integer, a match_negated of true, which the parser
// ignores and so reads with its meaning inverted, and a definition the
// parser reads as a slot or as a primitive constraint, which the model's
// definition cannot hold. The function's documentation lists each reading.
//
// # Hand-written companions
//
// Files named *_ext.go are reserved for hand-written method bodies
// and helpers. The generator never touches them. Generated files
// carry the standard "// Code generated by bmmgen; DO NOT EDIT."
// header and must not be edited by hand.
